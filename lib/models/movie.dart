class Movie {
  final String id;
  final String title;
  final String rating;
  final String description;
  final String imagePath;
  final String showtime;
  final double price;

  const Movie({
    required this.id,
    required this.title,
    required this.rating,
    required this.description,
    required this.imagePath,
    required this.showtime,
    required this.price,
  });
}
